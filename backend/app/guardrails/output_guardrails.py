"""Output Guardrails for ClothesSpot AI Customer Automation.

Validates model responses for:
1. Hallucination prevention (factual consistency against retrieved KB chunks)
2. Policy compliance and brand integrity
3. Sensitive data and internal prompt leakage prevention
4. Professional, empathetic customer tone
"""

import re
from typing import Any, Dict, List, Optional, Tuple


LEAKAGE_PATTERNS = [
    r"(?i)system\s+message",
    r"(?i)as\s+an\s+ai\s+language\s+model",
    r"(?i)my\s+instructions\s+are",
    r"(?i)RoundRobinGroupChat",
    r"(?i)TextMentionTermination",
    r"(?i)LOGGED",
    r"(?i)sk-[a-zA-Z0-9]{20,}",
]

POLICY_FACT_PATTERNS = [
    (r"\b30\s*days?\b", "refund_policy.md", "30-day return window"),
    (r"\b14\s*days?\b", "product_faq.md", "14-day replacement reporting window"),
    (r"\b15\s*minutes?\b", "account_and_login.md", "15-minute password reset link expiry"),
    (r"\b5\s*(?:to|-)\s*7\s*business\s*days?\b", "refund_policy.md", "5-7 business days refund processing"),
    (r"\b24\s*(?:to|-)\s*48\s*(?:business\s*)?hours?\b", "shipping_policy.md", "24-48 hours delivery update window"),
]


class OutputGuardrails:
    """Validates the final customer response generated by ResolutionAgent."""

    def __init__(self) -> None:
        pass

    def check_internal_leakage(self, response_text: str) -> Tuple[bool, Optional[str]]:
        """Check if internal agent prompt tokens, keys, or termination signals leaked."""
        for pattern in LEAKAGE_PATTERNS:
            if pattern == r"(?i)LOGGED":
                # Only a violation if the agent literally dumps LOGGED in customer facing response
                if re.search(r"\bLOGGED\b", response_text):
                    return True, "Response contains internal AutoGen termination token 'LOGGED'"
                continue
            if re.search(pattern, response_text):
                return True, f"Response contains internal system reference: {pattern}"
        return False, None

    def verify_groundedness(
        self,
        response_text: str,
        retrieved_passages: List[Dict[str, Any]],
        sources: List[str]
    ) -> Dict[str, Any]:
        """Verify that numerical claims or policy specifics are grounded in retrieved KB chunks."""
        combined_kb = " ".join([p.get("content", "") for p in retrieved_passages]).lower()
        resp_lower = response_text.lower()
        
        detected_claims: List[str] = []
        ungrounded_claims: List[str] = []

        measurable_claim_patterns = [
            r"\b\d+(?:\s*(?:to|-)\s*\d+)?\s*(?:business\s+)?(?:minutes?|hours?|days?|weeks?|months?|years?)\b",
            r"\$\s*\d+(?:\.\d{1,2})?",
        ]
        for pattern in measurable_claim_patterns:
            for match in re.finditer(pattern, resp_lower):
                claim = match.group(0)
                if claim not in detected_claims:
                    detected_claims.append(claim)
                if claim not in combined_kb:
                    ungrounded_claims.append(claim)

        for pattern, required_source, claim_name in POLICY_FACT_PATTERNS:
            if re.search(pattern, resp_lower):
                detected_claims.append(claim_name)
                # Check if the fact appears in retrieved KB text or expected source
                match_in_kb = re.search(pattern, combined_kb)
                if not match_in_kb:
                    ungrounded_claims.append(claim_name)

        is_grounded = (len(ungrounded_claims) == 0)
        return {
            "grounded": is_grounded,
            "detected_claims": detected_claims,
            "ungrounded_claims": ungrounded_claims,
            "hallucination_detected": not is_grounded,
        }

    def validate_response(
        self,
        response_text: str,
        retrieved_passages: List[Dict[str, Any]],
        sources: List[str]
    ) -> Dict[str, Any]:
        """Run all output guardrails."""
        if not response_text or len(response_text.strip()) < 10:
            return {
                "valid": False,
                "reason": "Response is too short or empty.",
                "hallucination_detected": False,
                "leakage_detected": False,
            }

        # 1. Leakage check
        has_leakage, leak_reason = self.check_internal_leakage(response_text)
        if has_leakage:
            return {
                "valid": False,
                "reason": f"Output guardrail failure: {leak_reason}",
                "hallucination_detected": False,
                "leakage_detected": True,
            }

        # 2. Groundedness check
        grounding_result = self.verify_groundedness(response_text, retrieved_passages, sources)

        grounded = grounding_result["grounded"]
        return {
            "valid": grounded,
            "reason": None if grounded else "Response contains policy claims not present in retrieved passages.",
            "groundedness": grounding_result,
            "hallucination_detected": grounding_result["hallucination_detected"],
            "leakage_detected": False,
        }
